class OfflineSyncQueue(db.Model):
    """Work that could not reach the cloud yet.

    A remote farm loses its link regularly, so an upload that fails must not
    lose the record. sync_engine enqueues the snapshot here and retries later,
    up to MAX_RETRIES.

    Example payload for operation_type "snapshot_upload":
        {"local_path": "captures/0001_20260828_071205.jpg",
         "snapshot_id": 42, "reason": "not_configured"}
    """

    __tablename__ = "offline_sync_queue"

    sync_id = db.Column(db.Integer, primary_key=True)
    device_id = db.Column(db.Integer, db.ForeignKey("biometric_devices.device_id"), nullable=True)
    worker_id = db.Column(db.Integer, db.ForeignKey("workers.id"), nullable=True)
    operation_type = db.Column(db.String(50), nullable=False)
    payload = db.Column(db.Text, nullable=False)
    sync_status = db.Column(db.String(20), default="pending", nullable=False)
    retry_count = db.Column(db.Integer, default=0, nullable=False)
    last_error = db.Column(db.Text, nullable=True)
    created_at = db.Column(db.DateTime, default=datetime.utcnow, nullable=False)
    synced_at = db.Column(db.DateTime, nullable=True)


