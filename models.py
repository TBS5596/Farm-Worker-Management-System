class Payroll(db.Model):
    """One worker's pay for one week. All amounts in ZMW.

    computed_from_attendance distinguishes a row generated from recorded
    sessions from a hand-entered correction. Either way the amounts are
    calculated by payroll_engine.compute_pay - only hours and a rate are input.

    napsa_rate and nhima_rate store the rates ACTUALLY USED, so a payslip stays
    reproducible after the rates change in Settings.

    Example row: 42 hours of which 2 overtime at 20.00/hour ->
        gross 860.00, NAPSA 43.00, NHIMA 8.60, net 808.40
    """

    __tablename__ = "payroll"

    payroll_id = db.Column(db.Integer, primary_key=True)
    worker_id = db.Column(db.Integer, db.ForeignKey("workers.id"), nullable=False)
    # The last day of the period this row covers. The column is named
    # week_ending for history - it predates any period other than a week, and
    # the additive-only migration cannot rename a column - but it now means
    # "period ending" for every cycle.
    week_ending = db.Column(db.Date, nullable=False)
    # The first day of the period, and which cycle produced it. Both are
    # recorded on the ROW rather than only read from Settings, because a farm
    # that switches from weekly to monthly still has to be able to read last
    # year's payslips: without these, a list showing 875 next to 3,400 is
    # unreadable and a worker will think they were short-paid.
    period_start = db.Column(db.Date, nullable=True)
    period_type = db.Column(db.String(20), nullable=True)
    total_hours = db.Column(db.Float, nullable=True)
    overtime_hours = db.Column(db.Float, nullable=True)
    hourly_rate = db.Column(db.Float, nullable=True)
    overtime_pay = db.Column(db.Float, nullable=True)
    gross_pay = db.Column(db.Float, nullable=True)
    napsa_rate = db.Column(db.Float, nullable=True)
    nhima_rate = db.Column(db.Float, nullable=True)
    napsa_deduction = db.Column(db.Float, nullable=True)
    nhima_deduction = db.Column(db.Float, nullable=True)
    net_pay = db.Column(db.Float, nullable=True)
    computed_from_attendance = db.Column(db.Boolean, default=False, nullable=False)
    generated_at = db.Column(db.DateTime, nullable=True)
    paid_status = db.Column(db.String(20), default="pending", nullable=False)
    payment_date = db.Column(db.Date, nullable=True)

    __table_args__ = (
        db.UniqueConstraint("worker_id", "week_ending", name="uq_payroll_worker_week"),
    )


